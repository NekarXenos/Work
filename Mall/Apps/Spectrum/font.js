/* The full 0..255 table the display reads. 0..31 are control codes and draw
   as blanks, 128..143 are the sixteen block graphics, 144..164 are the user
   defined graphics (A..U, which power on as the letter shapes), and the rest
   are the BASIC keyword tokens, which never reach the character renderer. */
export function buildFont() {
  const f = new Uint8Array(256 * 8);
  for (let i = 0; i < GLYPHS.length; i++) f.set(GLYPHS[i], (32 + i) * 8);
  /* Block graphics. The low four bits of the code are the quadrants, and
     the ROM takes them right before left: 1 upper right, 2 upper left,
     4 lower right, 8 lower left. So 131 is the top half and 143 is solid. */
  for (let n = 0; n < 16; n++) {
    const o = (128 + n) * 8;
    for (let r = 0; r < 8; r++) {
      const top = r < 4;
      const left = n & (top ? 2 : 8), right = n & (top ? 1 : 4);
      f[o + r] = (left ? 0xf0 : 0) | (right ? 0x0f : 0);
    }
  }
  return f;
}

/* UDGs power on holding the shapes of A..U */
export function defaultUDG(font) {
  const u = new Uint8Array(21 * 8);
  for (let i = 0; i < 21; i++) for (let r = 0; r < 8; r++) u[i * 8 + r] = font[(65 + i) * 8 + r];
  return u;
}

export const FONT = buildFont();
export const UDG_DEFAULT = defaultUDG(FONT);
